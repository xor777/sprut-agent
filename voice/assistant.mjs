export function sessionConfig(catalog, env) {
  return {
    type: "realtime",
    model: env.VOICE_MODEL || DEFAULT_MODEL,
    instructions: buildInstructions(catalog),
    tools: TOOLS,
    tool_choice: "auto",
    audio: {
      input: {
        noise_reduction: { type: "near_field" },
        transcription: {
          model: env.VOICE_TRANSCRIBE_MODEL || DEFAULT_TRANSCRIBE_MODEL,
          language: "ru",
        },
        turn_detection: {
          type: "semantic_vad",
          eagerness: "medium",
          create_response: true,
          interrupt_response: true,
        },
      },
      output: { voice: env.VOICE_VOICE || DEFAULT_VOICE },
    },
  };
}
